"""Builds data/data.js, the file the page loads its data from.

Run from the repository folder:   python3 build/make_data_js.py

Reads   data/colleges_slim.csv       one row per school (only the columns the page needs are kept)
        data/field_programs.csv      Bachelor's programs per school
        data/cip_names.csv           names of the four-digit CIP codes
        data/us_states_topo.json     U.S. state shapes (TopoJSON)
        js/variables.js              to find out which columns the page needs
Writes  data/data.js                 defines   const DATA = {colleges, fields, cip, topo}

Needs only the Python standard library.
"""
import csv, io, json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent

# columns the program itself needs, besides the ones listed in js/variables.js
BASE = ["UNITID", "INSTNM", "CITY", "STABBR", "ST_FIPS", "LATITUDE", "LONGITUDE", "Control", "Region", "Special"]

vars_js = (root / "js" / "variables.js").read_text(encoding="utf-8")
block = vars_js[vars_js.index("const VARIABLES=["):vars_js.index("const DEFAULT_VARIABLES")]
wanted = BASE + re.findall(r'^\s*\["([A-Za-z0-9_]+)",', block, flags=re.M)

with open(root / "data" / "colleges_slim.csv", encoding="utf-8", newline="") as f:
    rd = csv.DictReader(f)
    missing = [c for c in wanted if c not in rd.fieldnames]
    if missing:
        raise SystemExit("Columns named in js/variables.js but missing in colleges_slim.csv: " + ", ".join(missing))
    keep = [c for c in rd.fieldnames if c in wanted]
    out = io.StringIO(); w = csv.writer(out, lineterminator="\n"); w.writerow(keep)
    n = 0
    for row in rd:
        w.writerow([row[c] for c in keep]); n += 1

data = {
    "colleges": out.getvalue(),
    "fields": (root / "data" / "field_programs.csv").read_text(encoding="utf-8").replace("\r\n", "\n"),
    "cip": (root / "data" / "cip_names.csv").read_text(encoding="utf-8").replace("\r\n", "\n"),
    "topo": json.loads((root / "data" / "us_states_topo.json").read_text(encoding="utf-8")),
}
text = "/* Generated by build/make_data_js.py: do not edit by hand. */\nconst DATA = " + json.dumps(data, separators=(",", ":")) + ";\n"
(root / "data" / "data.js").write_text(text, encoding="utf-8")
print(f"data/data.js written: {n} schools, {len(keep)} columns, {len(text)/1e6:.2f} MB")
